import { join } from "node:path"

export const appRoot = join(import.meta.dir, "..")
export const repoRoot = join(appRoot, "..", "..")
export const outDir = join(appRoot, "dist")

export type Mode = "development" | "production"

export const mode = (): Mode => (Bun.env.NODE_ENV === "production" ? "production" : "development")

/**
 * Electron is provided by the runtime, never bundled. Bundling it produces a
 * multi-megabyte artifact that then fails at load, because the module it
 * inlined is a native binding the packaged app already has.
 */
export const ELECTRON_EXTERNAL = ["electron"]

/**
 * Pi and everything it drags in stay external and resolve from `node_modules`
 * at runtime.
 *
 * This is load-bearing, not a size optimization. Pi loads user extension
 * TypeScript through `jiti` from arbitrary absolute paths, and loads a WASM
 * image codec by path. Bundling would flatten both into a bundler's static
 * graph and break them inside the asar — which is precisely the failure mode
 * that dropping a compiled sidecar removed. Leaving Pi external preserves
 * ordinary Node resolution, which is what Pi is built and tested against.
 */
export const PI_EXTERNAL = ["@earendil-works/*", "jiti", "undici", "proper-lockfile", "@silvia-odwyer/*"]

export const banner = (label: string): string =>
  `// bake-pi ${label} bundle — generated by apps/desktop/build. Do not edit.`

export interface BuildReport {
  label: string
  outputs: { path: string; bytes: number }[]
  ms: number
}

export const runBuild = async (
  label: string,
  config: Parameters<typeof Bun.build>[0],
): Promise<BuildReport> => {
  const started = Bun.nanoseconds()
  const result = await Bun.build(config)
  if (!result.success) {
    for (const log of result.logs) console.error(log)
    throw new Error(`${label} build failed`)
  }
  return {
    label,
    outputs: result.outputs.map((output) => ({ path: output.path, bytes: output.size })),
    ms: Math.round((Bun.nanoseconds() - started) / 1e6),
  }
}

export const report = (reports: BuildReport[]): void => {
  for (const { label, outputs, ms } of reports) {
    const bytes = outputs.reduce((sum, output) => sum + output.bytes, 0)
    console.log(`  ${label.padEnd(12)} ${String(ms).padStart(5)} ms  ${(bytes / 1024).toFixed(1).padStart(9)} KiB`)
  }
}
